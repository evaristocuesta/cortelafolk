test('Runtime assets stay lightweight', () => {
	const assets = readdirSync(join(outputDirectory, '_astro'));
	const scriptBytes = assets.filter((file) => file.endsWith('.js')).reduce((total, file) => total + statSync(join(outputDirectory, '_astro', file)).size, 0);
	// The archive viewer and the consent banner ship inline. Shared boilerplate
	// (consent defaults, the banner) is identical on every page, so it is only
	// counted once: a visitor downloads each distinct script a single time.
	const inlineScripts = new Map();
	for (const source of [landingHtml, html, edicionesHtml]) {
		for (const match of source.matchAll(/<script\b([^>]*)>(.*?)<\/script>/gs)) {
			if (match[1].includes('application/ld+json')) continue;
			inlineScripts.set(match[2], Buffer.byteLength(match[2]));
		}
	}
	const inlineScriptBytes = [...inlineScripts.values()].reduce((total, bytes) => total + bytes, 0);
	assert.ok(scriptBytes + inlineScriptBytes < 12_000, `Client-side JavaScript is too large: ${scriptBytes + inlineScriptBytes} bytes.`);
	// Photographs may sit in year subfolders, so the budget walks the whole tree.
	const walk = (directory) => readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
		const fullPath = join(directory, entry.name);
		return entry.isDirectory() ? walk(fullPath) : [fullPath];
	});
	// Gallery thumbnails stay small; the large archive photographs may reach
	// 420 KB because they are 1600 px and only load when the viewer opens.
	for (const file of walk(join(outputDirectory, 'images'))) {
		if (!file.endsWith('.webp')) continue;
		const name = file.slice(outputDirectory.length + 1);
		const isThumbnail = name.includes('-thumb.webp');
		const isArchivePhoto = !isThumbnail && /(?:^|[\\/])20(?:24|25|26)(?:[\\/])/.test(name);
		const limit = isThumbnail ? 200_000 : isArchivePhoto ? 420_000 : 200_000;
		assert.ok(statSync(file).size < limit, `Unoptimised photograph (${statSync(file).size} bytes): ${name}`);
	}
});

