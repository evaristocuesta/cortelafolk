	assert.ok(shipped.includes('pointermove'), 'The drag-follow handling must ship with the archive page.');
	// Landscape photographs and tall posters must both arrive fully visible.
	// The media cell is a flex line (a grid item's auto row would leave the
	// strip's percentage height unresolved and clip a tall poster); the strip
	// fills it and each photograph is letterboxed inside its own cell, never
