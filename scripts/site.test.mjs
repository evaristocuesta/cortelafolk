const outputDirectory = resolve('dist');
const landingPath = join(outputDirectory, 'index.html');
const festivalPath = join(outputDirectory, '2027', 'index.html');
const cookiesPath = join(outputDirectory, 'cookies', 'index.html');
const privacyPath = join(outputDirectory, 'privacidad', 'index.html');
const editionsPath = join(outputDirectory, 'ediciones', 'index.html');
assert.ok(existsSync(landingPath) && existsSync(festivalPath) && existsSync(cookiesPath) && existsSync(privacyPath) && existsSync(editionsPath), 'Run pnpm build before pnpm test.');
// `html` is the full 2027 festival page; `landingHtml` is the simple root teaser.
const html = readFileSync(festivalPath, 'utf8');
const landingHtml = readFileSync(landingPath, 'utf8');
const cookiesHtml = readFileSync(cookiesPath, 'utf8');
const privacyHtml = readFileSync(privacyPath, 'utf8');
const edicionesHtml = readFileSync(editionsPath, 'utf8');
// Mechanical archive data (file names, thumbnails, dimensions), regenerated by
// `pnpm images`. The page must stay in step with it.
const editionImages = JSON.parse(readFileSync(resolve('src', 'data', 'edition-images.json'), 'utf8'));
const getAttribute = (tag, name) => tag.match(new RegExp(`\\b${name}="([^"]*)"`))?.[1];
// Camera filenames carry spaces, so their links arrive percent-encoded.
const distPath = (pathname) => join(outputDirectory, decodeURIComponent(pathname));
// global.css mirrors Tailwind's min-width breakpoints with a strict "<" so a
// fractional viewport (639.09px) can never fall outside both ranges. Lightning
// CSS emits that as its negated form, so both spellings are accepted.
const upperBound = (px) => `@media\\s*(?:\\(\\s*width\\s*<\\s*${px}px\\s*\\)|not all and \\(width>=${px}px\\))`;
const upperBoundBlock = (css, px) => css.match(new RegExp(`${upperBound(px)}[^{]*\\{(?:[^{}]|\\{[^{}]*\\})*\\}`))?.[0];
// Section slices shared by the profile and timetable tests.
const sliceBetween = (from, to) => html.slice(html.indexOf(from), html.indexOf(to));
const artistSection = () => sliceBetween('id="artistas"', 'id="actividades"');
const activitySection = () => sliceBetween('id="actividades"', 'id="free-access"');
// The timetable sits between `#programacion` and the stage strip that closes it.
const scheduleSlots = () => {
	const listStart = html.indexOf('id="programacion"');
	const stripStart = html.indexOf('<div class="stage-strip');
	assert.ok(listStart >= 0 && stripStart > listStart, 'The schedule and its stage strip must both exist.');
	return [...html.slice(listStart, stripStart).matchAll(/<li\b[\s\S]*?<\/li>/g)]
		.map((match) => match[0])
		.map((row) => {
			// Linked rows wrap their title in the modal trigger, so strip the markup.
			const heading = row.match(/<\/span><h4>([\s\S]*?)<\/h4>/)?.[1] ?? '';
			return {
				title: heading.replace(/<[^>]+>/g, '').trim(),
				category: row.match(/<span class="schedule-category">([^<]*)<\/span>/)?.[1] ?? '',
				stage: row.match(/<\/h4><p>([^<]*)<\/p>/)?.[1] ?? '',
				time: row.match(/<time\b[^>]*>([^<]*)<\/time>/)?.[1] ?? '',
				trigger: row.match(/<button\b[^>]*data-(?:artist|activity)-open[^>]*>/)?.[0],
			};
		});
};

