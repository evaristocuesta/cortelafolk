	for (const [attribute, label] of [['data-lightbox-prev', 'Imagen anterior'], ['data-lightbox-next', 'Imagen siguiente'], ['data-lightbox-close', 'Cerrar el visor']]) {
		const button = edicionesHtml.match(new RegExp(`<button\\b[^>]*${attribute}[^>]*>`))?.[0];
		assert.ok(button, `Missing ${attribute} control.`);
		assert.equal(getAttribute(button, 'type'), 'button');
		assert.equal(getAttribute(button, 'aria-label'), label, `${attribute} needs a Spanish accessible name.`);
	}
	// Triggers stay plain links: without JavaScript the photograph still opens.
	const triggers = [...edicionesHtml.matchAll(/<a\b[^>]*data-lightbox-open[^>]*>/g)];
	const expectedTriggers = 3 + Object.values(editionImages).reduce((total, data) => total + data.photos.length, 0);
	assert.equal(triggers.length, expectedTriggers, 'Three posters and every photograph must open the viewer.');
	for (const [tag] of triggers) {
		assert.match(getAttribute(tag, 'href') ?? '', /^\/images\//, 'Every trigger points at a real file.');
	}
	const lightboxScript = readFileSync(resolve('src/scripts/lightbox.ts'), 'utf8');
	assert.match(lightboxScript, /event\.key === 'ArrowLeft'/, 'The left arrow must step backwards.');
	assert.match(lightboxScript, /event\.key === 'ArrowRight'/, 'The right arrow must step forwards.');
	assert.match(lightboxScript, /showModal\(\)/, 'Triggers must open the dialog instead of navigating.');
	// Touch screens swipe between photographs: horizontal only, with a real
	// threshold so taps, vertical scrolls and mouse drags never change image.
	assert.match(lightboxScript, /addEventListener\('pointerdown'/, 'The viewer must track touch gestures.');
	assert.match(lightboxScript, /addEventListener\('pointermove'/, 'The photograph must follow the finger while dragging.');
	assert.match(lightboxScript, /addEventListener\('pointerup'/, 'The viewer must resolve touch gestures.');
	assert.match(lightboxScript, /pointerType !== 'touch'/, 'Only touch and pen gestures may swipe.');
	assert.match(lightboxScript, /Math\.abs\(dx\) > 40/, 'A swipe needs a deliberate horizontal distance.');
	assert.match(lightboxScript, /Math\.abs\(dx\) > Math\.abs\(dy\) \* 1\.5/, 'Mostly-vertical drags must stay scrolls.');
	assert.match(lightboxScript, /slide\(dx < 0 \? 1 : -1, dragX\)/, 'Swiping left advances, swiping right goes back.');
	// The gesture is a real carousel: a strip of three cells (previous,
	// current, next) translates with the finger, so the neighbour is already
	// on screen while dragging; a committed swipe slides the strip one cell
	// and re-centres it, a short drag settles back. Reduced motion keeps the
	// navigation but drops every animation.
	assert.match(edicionesHtml, /data-lightbox-track/, 'The viewer needs a sliding strip.');
	assert.match(edicionesHtml, /editions-lightbox-viewport/, 'The viewer needs a window that clips one cell.');
	assert.match(edicionesHtml, /data-lightbox-neighbor="prev"/, 'The previous photograph must sit beside the current one.');
	assert.match(edicionesHtml, /data-lightbox-neighbor="next"/, 'The next photograph must sit beside the current one.');
	assert.match(lightboxScript, /paint\(previous,/, 'The previous cell must be painted from its own trigger.');
	assert.match(lightboxScript, /paint\(next,/, 'The next cell must be painted from its own trigger.');
	// Re-centring rotates the roles of the three <img> elements instead of
	// rewriting the centre's source: the cell that already shows the incoming
	// photograph keeps its decoded bitmap, so no frame can flash the previous
	// one. Only the cell that ends up off-screen loads a new photograph.
	assert.match(lightboxScript, /const rotate = \(offset: number\)/, 'The strip must rotate cell roles on commit.');
	assert.match(lightboxScript, /image = wasNext;/, 'Advancing hands the centre to the next cell.');
	assert.match(lightboxScript, /image = wasPrevious;/, 'Going back hands the centre to the previous cell.');
	assert.match(lightboxScript, /if \(offset > 0\) paint\(next,/, 'Only the far cell is repainted after advancing.');
	assert.match(lightboxScript, /else paint\(previous,/, 'Only the far cell is repainted after going back.');
	assert.doesNotMatch(lightboxScript, /const step[\s\S]*?paint\(image,/, 'The centre photograph must never be rewritten on commit.');
	assert.match(lightboxScript, /const go = \(offset: number\) => \{ if \(!sliding\) slide\(offset\); \};/, 'Only one transition may run at a time.');
	assert.match(lightboxScript, /translateX\(\$\{x\}px\)/, 'The drag must translate the strip with the finger.');
	assert.match(lightboxScript, /prefers-reduced-motion: reduce/, 'The viewer must honour the reduced-motion preference.');
	assert.match(lightboxScript, /track\.animate\(/, 'Swipes must animate the strip, not just swap the photograph.');
	assert.match(lightboxScript, /exit\.onfinish/, 'The strip re-centres once the slide finishes.');
	assert.match(lightboxScript, /fill: 'forwards'/, 'The slide must hold its end state until the swap.');
	assert.match(lightboxScript, /exit\.cancel\(\);\s*move\(0\);\s*step\(offset\);/, 'The swap must be seamless: cancel, re-centre and repaint in one task.');
	// The slide travels one cell plus the gap between prints, measured from
	// the strip itself so the CSS gap is never duplicated in the script.
	assert.match(lightboxScript, /getBoundingClientRect\(\)/, 'The stride must be measured from the laid-out cells.');
	assert.match(lightboxScript, /Math\.abs\(there\.left - here\.left\)/, 'The stride spans from the current cell to the incoming one.');
	// The script ships with the page, inlined by the build.
	const shipped = [...edicionesHtml.matchAll(/<script type="module">([\s\S]*?)<\/script>/g)].map((match) => match[1]).join('');
	assert.ok(shipped.includes('ArrowLeft'), 'The viewer script must ship with the archive page.');
